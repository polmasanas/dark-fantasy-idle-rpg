using System;
using System.Globalization;
using System.IO;
using System.Text;
using DarkFantasy.Core.Combat;
using DarkFantasy.Core.Config;
using DarkFantasy.Core.Formulas;
using DarkFantasy.Core.Random;
using DarkFantasy.Core.Stats;

namespace DarkFantasy.Tools.BalanceSim
{
    /// <summary>
    /// M1 scope: a reference Fighter (level = boss level, all-Common gear at boss item level, no
    /// artifacts) fights each region's last subzone and boss with the real CombatEngine.
    /// The table shows where Common gear alone stops being enough, i.e. the wall prestige solves.
    /// Full player-profile simulation arrives with loot (M3) and prestige (M7).
    /// Usage: dotnet run --project Tools/BalanceSim.CSharp [-- regions normalFights bossFights]
    /// </summary>
    public static class Program
    {
        public static int Main(string[] args)
        {
            CultureInfo.DefaultThreadCurrentCulture = CultureInfo.InvariantCulture;
            CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
            int regions = args.Length > 0 ? int.Parse(args[0]) : 30;
            int normalFights = args.Length > 1 ? int.Parse(args[1]) : 2000;
            int bossFights = args.Length > 2 ? int.Parse(args[2]) : 500;

            string root = FindRepoRoot();
            var config = BalanceConfigLoader.FromJson(File.ReadAllText(Path.Combine(root, "Tools/BalanceSim/balance_config.json")));
            var f = new GameFormulas(config);
            var stats = new StatCalculator(config);
            var engine = new CombatEngine(config);
            var rng = new Pcg32(12345);

            var md = new StringBuilder();
            md.AppendLine("# C# combat check (real CombatEngine)");
            md.AppendLine();
            md.AppendLine("Generated by `Tools/BalanceSim.CSharp`. Reference Fighter: level = boss level, Common weapon and 6 Common armour pieces at boss item level, no artifacts, Python attribute template.");
            md.AppendLine();
            md.AppendLine("| Region | Boss lvl | Normal TTK (s) | Escape % | Boss win % | Boss mean fight (s) | Boss losses: died / timed out |");
            md.AppendLine("|---:|---:|---:|---:|---:|---:|---|");

            for (int r = 1; r <= regions; r++)
            {
                int bossLevel = f.BossLevel(r);
                var player = stats.Compute(ReferenceFighter(config, bossLevel));
                int subLevel = f.SubzoneLevel(r, config.World.SubzonesPerRegion);

                double ttkSum = 0; int escapes = 0, wins = 0;
                for (int i = 0; i < normalFights; i++)
                {
                    var res = engine.Resolve(player, Enemy(config, f, rng, subLevel, false), rng, false);
                    if (res.Outcome == FightOutcome.Won) { wins++; ttkSum += res.Duration; }
                    else escapes++;
                }

                int bossWins = 0, died = 0, timedOut = 0; double bossTime = 0;
                for (int i = 0; i < bossFights; i++)
                {
                    var res = engine.Resolve(player, Enemy(config, f, rng, bossLevel, true), rng, false);
                    bossTime += res.Duration;
                    if (res.Outcome == FightOutcome.Won) bossWins++;
                    else if (res.Outcome == FightOutcome.Died) died++;
                    else timedOut++;
                }

                md.AppendLine(string.Format(CultureInfo.InvariantCulture,
                    "| {0} | {1} | {2} | {3:0.0} | {4:0.0} | {5:0.0} | {6} / {7} |",
                    r, bossLevel, wins > 0 ? (ttkSum / wins).ToString("0.00", CultureInfo.InvariantCulture) : "-",
                    100.0 * escapes / normalFights, 100.0 * bossWins / bossFights, bossTime / bossFights, died, timedOut));
            }

            string outPath = Path.Combine(root, "Tools/BalanceSim/results/CSHARP_COMBAT.md");
            File.WriteAllText(outPath, md.ToString());
            Console.Write(md.ToString());
            Console.WriteLine("Written to " + outPath);
            return 0;
        }

        /// <summary>Same attribute template and gear model as balance_sim.py (Fighter, all Common).</summary>
        private static StatInputs ReferenceFighter(BalanceConfig c, int level)
        {
            double auto = c.Player.PointsPerLevelAuto * (level - 1);
            double manual = c.Player.PointsPerLevelManual * (level - 1);
            double growth = Math.Pow(c.Gear.ItemGrowth, level - 1);
            return new StatInputs
            {
                Class = ClassId.Fighter,
                Level = level,
                Primary = auto * 0.5 + manual,
                Vit = auto / 3,
                Def = auto / 12,
                CounterPoints = auto / 12,
                WeaponDamage = c.Gear.WeaponDmgBase * growth,
                GearArmour = 6 * c.Gear.ArmourBase * growth,
                GearHp = 6 * c.Gear.ArmourHpBase * growth,
            };
        }

        private static EnemySnapshot Enemy(BalanceConfig c, GameFormulas f, IRng rng, int level, bool boss) =>
            new EnemySnapshot
            {
                Hp = f.EnemyHp(level, boss) * rng.Range(c.Enemy.VarianceMultMin, c.Enemy.VarianceMultMax),
                Attack = f.EnemyAtk(level, boss),
                AttackInterval = c.Enemy.AttackIntervalS,
                Level = level,
                IsBoss = boss,
            };

        private static string FindRepoRoot()
        {
            var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
            while (dir != null && !File.Exists(Path.Combine(dir.FullName, "Tools/BalanceSim/balance_config.json")))
                dir = dir.Parent;
            if (dir == null) throw new InvalidOperationException("Run from inside the repository.");
            return dir.FullName;
        }
    }
}
