using System;
using System.Globalization;
using System.IO;
using System.Text;
using DarkFantasy.Core.Combat;
using DarkFantasy.Core.Config;
using DarkFantasy.Core.Formulas;
using DarkFantasy.Core.Random;
using DarkFantasy.Core.Stats;

namespace DarkFantasy.Tools.BalanceSim
{
    /// <summary>
    /// M1 scope: a reference Fighter (level = boss level, all-Common gear at boss item level, no
    /// artifacts) fights each region's last subzone and boss with the real CombatEngine.
    /// The table shows where Common gear alone stops being enough, i.e. the wall prestige solves.
    /// Full player-profile simulation arrives with loot (M3) and prestige (M7).
    /// Usage: dotnet run --project Tools/BalanceSim.CSharp [-- regions normalFights bossFights]
    /// </summary>
    public static class Program
    {
        public static int Main(string[] args)
        {
            CultureInfo.DefaultThreadCurrentCulture = CultureInfo.InvariantCulture;
            CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
            int regions = args.Length > 0 ? int.Parse(args[0]) : 30;
            int normalFights = args.Length > 1 ? int.Parse(args[1]) : 2000;
            int bossFights = args.Length > 2 ? int.Parse(args[2]) : 500;

            string root = FindRepoRoot();
            var config = BalanceConfigLoader.FromJson(File.ReadAllText(Path.Combine(root, "Tools/BalanceSim/balance_config.json")));
            config.Skills = SkillsConfigLoader.FromJson(File.ReadAllText(Path.Combine(root, "Tools/BalanceSim/skills_config.json")));
            var f = new GameFormulas(config);
            var stats = new StatCalculator(config);
            var engine = new CombatEngine(config);
            var rng = new Pcg32(12345);

            var md = new StringBuilder();
            md.AppendLine("# C# combat check (real CombatEngine)");
            md.AppendLine();
            md.AppendLine("Generated by `Tools/BalanceSim.CSharp`. Reference Fighter: level = boss level, Common weapon and 6 Common armour pieces at boss item level, no artifacts, Python attribute template.");
            md.AppendLine();
            md.AppendLine("| Region | Boss lvl | Normal TTK (s) | Escape % | Boss win % | Boss mean fight (s) | Boss losses: died / timed out |");
            md.AppendLine("|---:|---:|---:|---:|---:|---:|---|");

            for (int r = 1; r <= regions; r++)
            {
                int bossLevel = f.BossLevel(r);
                var player = stats.Compute(ReferenceFighter(config, bossLevel));
                int subLevel = f.SubzoneLevel(r, config.World.SubzonesPerRegion);

                double ttkSum = 0; int escapes = 0, wins = 0;
                for (int i = 0; i < normalFights; i++)
                {
                    var res = engine.Resolve(player, Enemy(config, f, rng, subLevel, false), rng, false);
                    if (res.Outcome == FightOutcome.Won) { wins++; ttkSum += res.Duration; }
                    else escapes++;
                }

                int bossWins = 0, died = 0, timedOut = 0; double bossTime = 0;
                for (int i = 0; i < bossFights; i++)
                {
                    var res = engine.Resolve(player, Enemy(config, f, rng, bossLevel, true), rng, false);
                    bossTime += res.Duration;
                    if (res.Outcome == FightOutcome.Won) bossWins++;
                    else if (res.Outcome == FightOutcome.Died) died++;
                    else timedOut++;
                }

                md.AppendLine(string.Format(CultureInfo.InvariantCulture,
                    "| {0} | {1} | {2} | {3:0.0} | {4:0.0} | {5:0.0} | {6} / {7} |",
                    r, bossLevel, wins > 0 ? (ttkSum / wins).ToString("0.00", CultureInfo.InvariantCulture) : "-",
                    100.0 * escapes / normalFights, 100.0 * bossWins / bossFights, bossTime / bossFights, died, timedOut));
            }

            AppendClassTable(md, config, f, stats, Math.Min(regions, 8), normalFights / 4, bossFights / 2);
            AppendSkillTable(md, config, f, stats, normalFights / 4, bossFights / 2);

            string outPath = Path.Combine(root, "Tools/BalanceSim/results/CSHARP_COMBAT.md");
            File.WriteAllText(outPath, md.ToString());
            Console.Write(md.ToString());
            Console.WriteLine("Written to " + outPath);
            return 0;
        }

        /// <summary>
        /// M5: each class at the same reference (level = boss level, Common class weapon and armour) against
        /// the real families (EnemyFactory: archetypes, elements, evasion) — mean normal fight over subzones
        /// 1-5 and boss win rate.
        /// </summary>
        private static void AppendClassTable(StringBuilder md, BalanceConfig c, GameFormulas f, StatCalculator stats,
            int regions, int normalFights, int bossFights)
        {
            var engine = new CombatEngine(c);
            var enemies = new DarkFantasy.Core.World.EnemyFactory(c);
            var rng = new Pcg32(777);
            md.AppendLine();
            md.AppendLine("## Classes against the families (M5)");
            md.AppendLine();
            md.AppendLine("| Region | Family (sub 1) | Fighter fight (s) | Archer fight (s) | Mage fight (s) | Fighter boss win % | Archer boss win % | Mage boss win % |");
            md.AppendLine("|---:|---|---:|---:|---:|---:|---:|---:|");
            for (int r = 1; r <= regions; r++)
            {
                int bossLevel = f.BossLevel(r);
                var fights = new string[3];
                var bosses = new string[3];
                foreach (ClassId cls in Enum.GetValues(typeof(ClassId)))
                {
                    var player = stats.Compute(ReferenceHero(c, cls, bossLevel));
                    double t = 0; int n = 0;
                    for (int sub = 1; sub <= c.World.SubzonesPerRegion; sub++)
                    {
                        int lvl = f.SubzoneLevel(r, sub);
                        for (int i = 0; i < normalFights; i++)
                        {
                            var res = engine.Resolve(player, enemies.Create(new DarkFantasy.Core.World.Encounter(r, sub, lvl, false), rng), rng, false);
                            t += res.Duration; n++;
                        }
                    }
                    int wins = 0;
                    for (int i = 0; i < bossFights; i++)
                        if (engine.Resolve(player, enemies.Create(new DarkFantasy.Core.World.Encounter(r, 5, bossLevel, true), rng), rng, false).Outcome == FightOutcome.Won)
                            wins++;
                    fights[(int)cls] = (t / n).ToString("0.00", CultureInfo.InvariantCulture);
                    bosses[(int)cls] = (100.0 * wins / bossFights).ToString("0.0", CultureInfo.InvariantCulture);
                }
                string family = enemies.FamilyFor(new DarkFantasy.Core.World.Encounter(r, 1, 1, false)).Id;
                md.AppendLine($"| {r} | {family} | {fights[0]} | {fights[1]} | {fights[2]} | {bosses[0]} | {bosses[1]} | {bosses[2]} |");
            }
        }

        /// <summary>
        /// M6: effective damage per second gained from skills, per class, with points spent by the suggested order
        /// (level = boss level; "full" = the whole 52-point tree on the region 5 reference). Normal fights are
        /// played back to back with cooldowns carried over and the respawn gap counted (M6-2).
        /// Gain = mean fight time without skills / with skills − 1. Boss columns: win rate without → with.
        /// </summary>
        private static void AppendSkillTable(StringBuilder md, BalanceConfig c, GameFormulas f, StatCalculator stats,
            int normalFights, int bossFights)
        {
            var engine = new CombatEngine(c);
            var enemies = new DarkFantasy.Core.World.EnemyFactory(c);
            var tree = new DarkFantasy.Core.Skills.SkillTree(c);
            var build = new DarkFantasy.Core.Skills.SkillBuild(c);
            md.AppendLine();
            md.AppendLine("## Skills (M6)");
            md.AppendLine();
            md.AppendLine("DPS gain = effective damage per second gained from the Common tree against the region's enemies (points by the suggested order, cooldowns carried, 30 s fights against a target that cannot die, so whole-hit rounding does not hide the change). Fight gain = mean normal fight time without / with skills − 1 (whole hits). Boss: win rate without → with skills.");
            md.AppendLine();
            md.AppendLine("| Reference | Points | Fighter DPS gain | Archer DPS gain | Mage DPS gain | Fighter fight gain | Archer fight gain | Mage fight gain | Fighter boss | Archer boss | Mage boss |");
            md.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---|---|---|");
            var rows = new (string name, int region, int rankLevel)[] { ("R2", 2, 0), ("R3", 3, 0), ("R4", 4, 0), ("R5", 5, 0), ("R5 full tree", 5, 260) };
            foreach (var row in rows)
            {
                int bossLevel = f.BossLevel(row.region);
                var gains = new string[3];
                var dps = new string[3];
                var boss = new string[3];
                int points = 0;
                foreach (ClassId cls in Enum.GetValues(typeof(ClassId)))
                {
                    var hero = DarkFantasy.Core.Characters.CharacterState.Create(cls);
                    hero.Level = row.rankLevel > 0 ? row.rankLevel : bossLevel;
                    tree.AutoSpend(hero);
                    points = tree.Spent(hero);
                    var plainInputs = ReferenceHero(c, cls, bossLevel);
                    var plain = stats.Compute(plainInputs);
                    var skilledInputs = ReferenceHero(c, cls, bossLevel);
                    build.AddStats(hero, skilledInputs);
                    var skilled = stats.Compute(skilledInputs);
                    var kit = build.Kit(hero);

                    double tPlain = 0, tSkill = 0;
                    var cds = new double[kit.Actives.Count];
                    var rngA = new Pcg32(4242);
                    var rngB = new Pcg32(4242);
                    for (int i = 0; i < normalFights; i++)
                        for (int sub = 1; sub <= c.World.SubzonesPerRegion; sub++)
                        {
                            var enc = new DarkFantasy.Core.World.Encounter(row.region, sub, f.SubzoneLevel(row.region, sub), false);
                            var ea = enemies.Create(enc, rngA);
                            var eb = enemies.Create(enc, rngB);
                            tPlain += engine.Resolve(plain, ea, rngA, false).Duration + c.Combat.EnemyRespawnS;
                            var r = engine.Resolve(skilled, eb, rngB, false, kit, cds);
                            tSkill += r.Duration + c.Combat.EnemyRespawnS;
                            for (int k = 0; k < cds.Length; k++) cds[k] = Math.Max(0, cds[k] - c.Combat.EnemyRespawnS);
                        }
                    gains[(int)cls] = (tPlain / tSkill - 1).ToString("+0%;-0%", CultureInfo.InvariantCulture);
                    dps[(int)cls] = (DamageRate(engine, enemies, skilled, kit, row.region, c) / DamageRate(engine, enemies, plain, null, row.region, c) - 1)
                        .ToString("+0%;-0%", CultureInfo.InvariantCulture);

                    int winsPlain = 0, winsSkill = 0;
                    var bossEnc = new DarkFantasy.Core.World.Encounter(row.region, 5, bossLevel, true);
                    for (int i = 0; i < bossFights; i++)
                    {
                        if (engine.Resolve(plain, enemies.Create(bossEnc, rngA), rngA, false).Outcome == FightOutcome.Won) winsPlain++;
                        if (engine.Resolve(skilled, enemies.Create(bossEnc, rngB), rngB, false, kit, new double[kit.Actives.Count]).Outcome == FightOutcome.Won) winsSkill++;
                    }
                    boss[(int)cls] = string.Format(CultureInfo.InvariantCulture, "{0:0}% → {1:0}%", 100.0 * winsPlain / bossFights, 100.0 * winsSkill / bossFights);
                }
                md.AppendLine($"| {row.name} | {points} | {dps[0]} | {dps[1]} | {dps[2]} | {gains[0]} | {gains[1]} | {gains[2]} | {boss[0]} | {boss[1]} | {boss[2]} |");
            }
        }

        /// <summary>Damage per second over many 30 s fights against the region's enemies made unkillable.</summary>
        private static double DamageRate(CombatEngine engine, DarkFantasy.Core.World.EnemyFactory enemies, CombatStats player,
            DarkFantasy.Core.Skills.SkillKit kit, int region, BalanceConfig c)
        {
            var f = new GameFormulas(c);
            var rng = new Pcg32(99);
            double damage = 0, time = 0;
            var cds = kit == null ? null : new double[kit.Actives.Count];
            for (int i = 0; i < 40; i++)
                for (int sub = 1; sub <= c.World.SubzonesPerRegion; sub++)
                {
                    var e = enemies.Create(new DarkFantasy.Core.World.Encounter(region, sub, f.SubzoneLevel(region, sub), false), rng);
                    e.Hp = 1e300;
                    var r = kit == null ? engine.Resolve(player, e, rng, true) : engine.Resolve(player, e, rng, true, kit, cds);
                    foreach (var ev in r.Events)
                        if (ev.Type == CombatEventType.PlayerHit || ev.Type == CombatEventType.PlayerCrit || ev.Type == CombatEventType.Counter
                            || ev.Type == CombatEventType.SkillHit || ev.Type == CombatEventType.SkillCrit || ev.Type == CombatEventType.DotTick)
                            damage += ev.Amount;
                    time += r.Duration;
                }
            return damage / time;
        }

        /// <summary>Class template (growth pattern averaged), all manual points into the primary, Common class weapon and armour.</summary>
        private static StatInputs ReferenceHero(BalanceConfig c, ClassId cls, int level)
        {
            var inputs = new StatInputs { Class = cls, Level = level };
            var pattern = c.Classes[cls].GrowthPattern;
            int levels = level - 1;
            foreach (var row in pattern)
                foreach (var a in row)
                {
                    double v = levels / (double)pattern.Length;
                    switch (a)
                    {
                        case DarkFantasy.Core.Characters.AttributeId.Str:
                        case DarkFantasy.Core.Characters.AttributeId.Dex:
                        case DarkFantasy.Core.Characters.AttributeId.Int: inputs.Primary += v; break;
                        case DarkFantasy.Core.Characters.AttributeId.Vit: inputs.Vit += v; break;
                        case DarkFantasy.Core.Characters.AttributeId.Def: inputs.Def += v; break;
                        case DarkFantasy.Core.Characters.AttributeId.CritChance: inputs.CritPoints += v; break;
                        case DarkFantasy.Core.Characters.AttributeId.CritDamage: inputs.CritDamagePoints += v; break;
                        case DarkFantasy.Core.Characters.AttributeId.Counter: inputs.CounterPoints += v; break;
                    }
                }
            inputs.Primary += c.Player.PointsPerLevelManual * levels;
            var gear = new DarkFantasy.Core.Items.GearStats(c);
            var weapon = new DarkFantasy.Core.Items.ItemInstance { Kind = DarkFantasy.Core.Items.ItemKind.MainHand, TypeId = c.Items.StarterTypes[cls], ItemLevel = level, Rarity = DarkFantasy.Core.Items.Rarity.Common };
            gear.Apply(inputs, new[] { weapon }, cls);
            double growth = Math.Pow(c.Gear.ItemGrowth, level - 1);
            inputs.GearArmour += 6 * c.Gear.ArmourBase * growth;
            inputs.GearHp += 6 * c.Gear.ArmourHpBase * growth;
            return inputs;
        }

        /// <summary>Same attribute template and gear model as balance_sim.py (Fighter, all Common).</summary>
        private static StatInputs ReferenceFighter(BalanceConfig c, int level)
        {
            double auto = c.Player.PointsPerLevelAuto * (level - 1);
            double manual = c.Player.PointsPerLevelManual * (level - 1);
            double growth = Math.Pow(c.Gear.ItemGrowth, level - 1);
            return new StatInputs
            {
                Class = ClassId.Fighter,
                Level = level,
                Primary = auto * 0.5 + manual,
                Vit = auto / 3,
                Def = auto / 12,
                CounterPoints = auto / 12,
                WeaponDamage = c.Gear.WeaponDmgBase * growth,
                GearArmour = 6 * c.Gear.ArmourBase * growth,
                GearHp = 6 * c.Gear.ArmourHpBase * growth,
            };
        }

        private static EnemySnapshot Enemy(BalanceConfig c, GameFormulas f, IRng rng, int level, bool boss) =>
            new EnemySnapshot
            {
                Hp = f.EnemyHp(level, boss) * rng.Range(c.Enemy.VarianceMultMin, c.Enemy.VarianceMultMax),
                Attack = f.EnemyAtk(level, boss),
                AttackInterval = c.Enemy.AttackIntervalS,
                Level = level,
                IsBoss = boss,
            };

        private static string FindRepoRoot()
        {
            var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
            while (dir != null && !File.Exists(Path.Combine(dir.FullName, "Tools/BalanceSim/balance_config.json")))
                dir = dir.Parent;
            if (dir == null) throw new InvalidOperationException("Run from inside the repository.");
            return dir.FullName;
        }
    }
